import h5py
import numpy as np

# ==============================================================================
# 1. КОНСТАНТЫ И ПАРАМЕТРЫ МОДЕЛИ (из таблицы)
# ==============================================================================
R = 0.05  # Радиус шара, м
t_max = 15*1e4  # Максимальное время, с
rho = 1670.0  # Плотность вещества, кг/м³
c = 1682.0  # Теплоёмкость, Дж/(кг·К)
lam = 0.29  # Теплопроводность, Вт/(м·К)
alpha = 5.0  # Коэффициент теплоотдачи, Вт/(м²·К)
T_e = 368.0  # Внешняя/начальная температура, К
Q = 1.1972e6  # Тепловой эффект, Дж/кг
Z = 4.0e17  # Предэкспоненциальный множитель, 1/с
E = 1.6263e5  # Энергия активации, Дж/моль
eta_0 = 0.1  # Степень автокаталитичности
R_0 = 8.3144126  # Универсальная газовая постоянная, Дж/(К·моль)

# Параметры сетки
N = 100  # Число узлов по радиусу

# Параметры адаптивного шага по времени
dt_start = 10.0  # Начальный шаг, с
dT_target = 0.2  # Желаемое изменение температуры за шаг, К
dt_min = 1e-6  # Минимальный шаг, с
dt_max = 500.0  # Максимальный шаг, с

# ==============================================================================
# 2. ПОСТРОЕНИЕ НЕРАВНОМЕРНОЙ СЕТКИ ПО РАДИУСУ
# ==============================================================================
# Используем квадратичное сгущение к центру (r = 0)
xi = np.linspace(0, 1, N)
r = R * (xi**2)

# Вычисляем шаги между узлами
dr = np.diff(r)  # Длина N-1

# ==============================================================================
# 3. ФУНКЦИИ ДЛЯ ЧИСЛЕННЫХ МЕТОДОВ
# ==============================================================================


# Правая часть кинетического уравнения: d_eta/dt = f(eta, T)
def kinetic_f(eta, T):
    # Предотвращаем деление на ноль и переполнение экспоненты
    T = np.maximum(T, 1e-3)
    # Ограничиваем eta сверху единицей
    eta_clipped = np.clip(eta, 0.0, 1.0)

    # Уравнение: (eta + eta_0) * (1 - eta) * Z * exp(-E / (R_0 * T))
    return (
        (eta_clipped + eta_0)
        * (1.0 - eta_clipped)
        * Z
        * np.exp(-E / (R_0 * T))
    )


# Метод Рунге-Кутты 4-го порядка (RK4) для кинетики во всех узлах
def rk4_step(eta_old, T, dt):
    k1 = kinetic_f(eta_old, T)
    k2 = kinetic_f(eta_old + 0.5 * dt * k1, T)
    k3 = kinetic_f(eta_old + 0.5 * dt * k2, T)
    k4 = kinetic_f(eta_old + dt * k3, T)

    eta_new = eta_old + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
    return np.clip(eta_new, 0.0, 1.0)


# Метод прогонки для решения трехдиагональной СЛАУ
# ==============================================================================
# ИСПРАВЛЕННЫЙ БЛОК: Метод прогонки для решения трехдиагональной СЛАУ
# ==============================================================================
def thomas_algorithm(A, B, C, F):
    n = len(F)
    alpha_p = np.zeros(n)
    beta_p = np.zeros(n)
    X = np.zeros(n)

    # Инициализация первого узла (i = 0) с защитой от деления на ноль
    if abs(B[0]) > 1e-15:
        alpha_p[0] = -C[0] / B[0]
        beta_p[0] = F[0] / B[0]
    else:
        alpha_p[0] = 0.0
        beta_p[0] = F[0]

    # Прямой ход прогонки
    for i in range(1, n - 1):
        denom = B[i] + A[i] * alpha_p[i - 1]
        alpha_p[i] = -C[i] / denom
        beta_p[i] = (F[i] - A[i] * beta_p[i - 1]) / denom

    # Для последнего узла i = n-1
    denom = B[n - 1] + A[n - 1] * alpha_p[n - 2]
    X[n - 1] = (F[n - 1] - A[n - 1] * beta_p[n - 2]) / denom

    # Обратный ход прогонки
    for i in range(n - 2, -1, -1):
        X[i] = alpha_p[i] * X[i + 1] + beta_p[i]

    return X



# ==============================================================================
# 4. ИНИЦИАЛИЗАЦИЯ И СТАРТ РАСЧЁТА
# ==============================================================================
T = np.full(N, T_e)  # Начальная температура во всех узлах
eta = np.zeros(N)  # Начальная степень распада

t = 0.0
dt = dt_start

# Создаем файл HDF5 для записи результатов
with h5py.File("simulation_results.h5", "w") as h5f:
    # Сохраняем координатную сетку, так как она неизменна
    h5f.create_dataset("radius", data=r)

    # Создаем динамические массивы с возможностью расширения (resizable)
    dt_t = h5py.special_dtype(vlen=str)  # Для совместимости типов, если нужно
    h5_t = h5f.create_dataset("time", (0,), maxshape=(None,), dtype="f8")
    h5_T = h5f.create_dataset("temperature", (0, N), maxshape=(None, N), dtype="f8")
    h5_eta = h5f.create_dataset("eta", (0, N), maxshape=(None, N), dtype="f8")

    step = 0
    print("Запуск численного моделирования...")

    while t < t_max:
        # --- Шаг 1. Расчёт кинетики (Рунге-Кутта) ---
        # Считаем новое значение eta_pred на основе текущей температуры T
        eta_pred = rk4_step(eta, T, dt)

        # Вычисляем источник тепла (скорость тепловыделения на данном шаге)
        # d_eta/dt ≈ (eta_pred - eta) / dt
        W = rho * Q * (eta_pred - eta) / dt

        # --- Шаг 2. Расчёт теплопроводности (Метод прогонки) ---
        # Формируем коэффициенты трехдиагональной матрицы A_i * T_{i-1} + B_i * T_i + C_i * T_{i+1} = F_i
        A_mat = np.zeros(N)
        B_mat = np.zeros(N)
        C_mat = np.zeros(N)
        F_mat = np.zeros(N)

        # Узел i = 0 (Центр шара, граничное условие симметрии: dT/dr = 0)
        # Аппроксимация с учетом раскрытия неопределенности (2/r)*(dT/dr) -> 3 * d²T/dr²
        # Используем формулу для неравномерной сетки между r[0] и r[1]
        dr0 = dr[0]
        A_mat[0] = 0.0
        B_mat[0] = -(rho * c / dt + 6 * lam / (dr0**2))
        C_mat[0] = 6 * lam / (dr0**2)
        F_mat[0] = -rho * c * T[0] / dt - W[0]

        # Внутренние узлы i = 1 ... N-2
        for i in range(1, N - 1):
            h_l = dr[i - 1]  # Шаг слева r_i - r_{i-1}
            h_r = dr[i]  # Шаг справа r_{i+1} - r_i
            r_i = r[i]

            # Оператор теплопроводности на неравномерной сетке для сферических координат
            term_diff = (2.0 * lam) / (h_l + h_r)
            term_coord = (2.0 * lam) / r_i

            A_mat[i] = term_diff * (2.0 / h_l) - term_coord * (1.0 / (h_l + h_r))
            C_mat[i] = term_diff * (2.0 / h_r) + term_coord * (1.0 / (h_l + h_r))
            B_mat[i] = -(rho * c / dt + A_mat[i] + C_mat[i])
            F_mat[i] = -rho * c * T[i] / dt - W[i]

        # Узел i = N-1 (Поверхность шара, третье граничное условие)
        # -lam * dT/dr = alpha * (T - T_e)
        h_l = dr[-1]  # Шаг между узлами N-2 и N-1
        r_N = r[N - 1]

        # Коэффициенты, учитывающие теплоемкость граничного узла и честную теплоотдачу
        A_mat[N - 1] = (2.0 * lam) / (h_l ** 2) - (2.0 * lam) / (r_N * h_l)

        B_mat[N - 1] = -(
                rho * c / dt
                + (2.0 * lam) / (h_l ** 2)
                - (2.0 * lam) / (r_N * h_l)
                + (2.0 * alpha) / h_l
        )

        F_mat[N - 1] = (
                - rho * c * T[N - 1] / dt
                - W[N - 1]
                - (2.0 * alpha / h_l) * T_e
        )

        # Решаем СЛАУ для поиска новых температур
        T_pred = thomas_algorithm(A_mat, B_mat, C_mat, F_mat)

        # --- Шаг 3. Адаптивный контроль шага по времени ---
        delta_T_max = np.max(np.abs(T_pred - T))

        # Критический скачок температуры — отбрасываем шаг
        if delta_T_max > 2.0 * dT_target and dt > dt_min:
            dt = max(dt * 0.5, dt_min)
            continue  # Возвращаемся в начало цикла, не сохраняя данные

        # Шаг принят — обновляем физические поля
        T = np.copy(T_pred)
        eta = np.copy(eta_pred)
        t += dt

        # Записываем данные в файл HDF5
        h5_t.resize((step + 1,))
        h5_T.resize((step + 1, N))
        h5_eta.resize((step + 1, N))

        h5_t[step] = t
        h5_T[step, :] = T
        h5_eta[step, :] = eta

        step += 1

        # Вычисляем величину следующего шага
        if delta_T_max > 0:
            dt_next = dt * (dT_target / delta_T_max)
        else:
            dt_next = dt * 2.0

        dt = min(max(dt_next, dt_min), dt_max)

        # Вывод прогресса в консоль
        if step % 500 == 0 or t >= t_max:
            print(
                f"Время: {t:.2f} c | Шаг dt: {dt:.5f} c | Т в центре: {T[0]:.1f} K | eta в центре: {eta[0]:.4f}"
            )

print(f"\nРасчёт успешно завершён! Всего шагов сохранено: {step}")
print("Все данные находятся в файле 'simulation_results.h5'.")
