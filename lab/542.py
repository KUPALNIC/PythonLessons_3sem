import matplotlib.pyplot as plt
import numpy as np

# 1. Исходные экспериментальные данные
J = np.array([
    0.00, 0.20, 0.40, 0.60, 0.80, 1.00, 1.20, 1.40, 1.60, 1.80,
    2.00, 2.20, 2.40, 2.60, 2.80, 3.00, 3.20, 3.40, 3.50, 3.55,
    3.60, 3.65, 3.70, 3.80, 4.00, 4.20, 4.40
])

N = np.array([
    1.812, 1.762, 1.724, 1.887, 2.236, 3.823, 6.410, 8.609, 10.783, 12.357,
    13.057, 13.694, 13.381, 10.995, 8.296, 5.273, 3.224, 8.209, 16.343, 22.290,
    24.102, 23.265, 23.002, 14.843, 2.749, 0.975, 0.637
])

m0c2 = 511.0  # Масса покоя электрона, кэВ
N_phi = 1.000  # Темновой фон детектора

# 2. Пересчет в физические релятивистские величины
p = 279.05 * J  # Импульс, кэВ/с
T = np.sqrt(p**2 + m0c2**2) - m0c2  # Кинетическая энергия, кэВ

# Расчет чистой скорости счета
N_clean = N - N_phi


# Функция Ферми-Кюри (исключаем деление на 0 и отрицательные значения под корнем)
with np.errstate(divide='ignore', invalid='ignore'):
    F_K = np.sqrt(N_clean / p**3)
    # Для первой точки p=0 зануляем вручную
    F_K[0] = 0
    # Там, где значения ушли под фон, зануляем
    F_K[N_clean <= 0] = 0

# 3. Выделение линейного участка для МНК (точки с 7 по 17 включительно, ток 1.2А - 3.2А)
mask = (J >= 2.2) & (J <= 3.0)
T_fit = T[mask]
F_K_fit = F_K[mask]

# Линейная регрессия по МНК (y = a*x + b)
poly, cov = np.polyfit(T_fit, F_K_fit, 1, cov=True)
a, b = poly

# Расчет точки пересечения с осью X (F_K = 0 -> T_max = -b/a)
T_max = -b / a

# Расчет погрешности T_max методом переноса ошибок из ковариационной матрицы
sigma_a = np.sqrt(cov[0, 0])
sigma_b = np.sqrt(cov[1, 1])
sigma_Tmax = T_max * np.sqrt((sigma_a / a)**2 + (sigma_b / b)**2)

print(f"Результат расчета:")
print(f"Максимальная энергия распада T_max = {T_max:.1f} ± {sigma_Tmax:.1f} кэВ")

# 4. Построение графика
plt.figure(figsize=(8, 5.5))
plt.grid(True, linestyle='--', alpha=0.5)

# Экспериментальные точки
plt.scatter(T, F_K*10**6, color='blue', edgecolors='black', label='Эксперимент', zorder=3)

# Линия аппроксимации МНК
T_line = np.linspace(50, T_max + 50, 100)
F_K_line = a * T_line + b
plt.plot(T_line, F_K_line*10**6, 'r--', label=f'Аппроксимация МНК ($T_{{max}}$ = {T_max:.1f} кэВ)')

# Вертикальная линия на T_max
plt.axvline(T_max, color='green', linestyle=':', linewidth=1.5, label=f'$T_{{max}}$')

# Настройка осей
plt.xlim(0, 700)
plt.ylim(0, 1000)
plt.xlabel('Кинетическая энергия электронов $T$, кэВ', fontsize=11)
plt.ylabel('Функция Ферми-Кюри $F_K$, отн. ед.', fontsize=11)
plt.title('Определение граничной энергии $T_{max}$ (График Ферми-Кюри)', fontsize=12, fontweight='bold')
plt.legend()
plt.show()
