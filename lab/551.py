import numpy as np
import matplotlib.pyplot as plt

# =============================================================================
# 1. ВХОДНЫЕ ЭКСПЕРИМЕНТАЛЬНЫЕ ДАННЫЕ ИЗ ТАБЛИЦЫ
# =============================================================================

# Измерение фона (последняя строчка таблицы)
t_bg = 420.0  # время измерения фона, с
N_bg = 19348.0  # число импульсов фона
I_bg = N_bg / t_bg  # скорость счета фона, имп/с
# ИСПРАВЛЕНО: По закону Пуассона ошибка количества импульсов dN = sqrt(N). Тогда dI = sqrt(N)/t
dI_bg = np.sqrt(N_bg) / t_bg

# Измерение интенсивности потока без поглотителя (l = 0) (первая строчка таблицы)
t_0 = 60.0  # время измерения, с
N_0 = 566630.0  # число импульсов без поглотителя
I_0 = (N_0 / t_0) - I_bg  # чистая скорость счета без поглотителя, имп/с
dI_0_raw = np.sqrt(N_0) / t_0
dI_0 = np.sqrt(dI_0_raw ** 2 + dI_bg ** 2)  # Полная погрешность I_0 с учетом фона

# Массивы данных для исследуемых материалов (Fe, Pb, Al)
data = {
    'Железо (Fe)': {
        'l': np.array([10.1, 20.22, 30.4, 40.3, 50.2, 60.4, 70.5, 80.6, 90.7]),
        't': np.array([60, 60, 90, 120, 180, 300, 480, 690, 900]),
        'N': np.array([321267, 182811, 156976, 121258, 109130, 111108, 112269, 106194, 100995]),
        'color': '#1f77b4'
    },
    'Свинец (Pb)': {
        # Точка l = 190 мм исключена из МНК как сильный выброс
        'l': np.array([4.7, 9.8, 14.6, 19.32, 24.42, 29.46, 34.28]),
        't': np.array([60, 60, 120, 120, 240, 360, 600]),
        'N': np.array([332460, 187705, 220826, 128428, 150902, 136927, 141477]),
        'color': '#d62728'
    },
    'Алюминий (Al)': {
        'l': np.array([20.2, 40.12, 60.28, 80.4, 100.5, 120.24]),
        't': np.array([60, 60, 60, 120, 120, 150]),
        'N': np.array([385991, 255910, 169683, 228534, 155371, 131921]),
        'color': '#2ca02c'
    }
}

# =============================================================================
# 2. ПОСТРОЕНИЕ ОТДЕЛЬНЫХ ГРАФИКОВ И АНАЛИТИЧЕСКИЙ РАСЧЕТ МНК С ПОГРЕШНОСТЬЮ mu
# =============================================================================

print("=" * 75)
print(f"{'Материал':<15} | {'mu, см^-1':<12} | {'Погрешность d_mu, см^-1':<23} | {'Отн. ошибка':<10}")
print("=" * 75)

for title, material_data in data.items():
    l_cm = material_data['l'] / 10.0  # мм -> см
    t = material_data['t']
    N = material_data['N']
    n = len(l_cm)  # Число точек для данного материала

    # Расчет чистой скорости счета
    I_raw = N / t
    I = I_raw - I_bg

    # Логарифм отношения интенсивностей (y = ln(I_0 / I))
    y = np.log(I_0 / I)

    # ИСПРАВЛЕНО: Погрешность dy для функции y = ln(I_0) - ln(I)
    # Квадратично складываем относительные ошибки независимых величин I и I_0
    dI_raw = np.sqrt(N) / t
    dI = np.sqrt(dI_raw ** 2 + dI_bg ** 2)  # полная погрешность текущей интенсивности с учетом фона
    dy = np.sqrt((dI_0 / I_0) ** 2 + (dI / I) ** 2)

    # Линейный регрессионный анализ (МНК) вручную для вычисления точных погрешностей
    # Уравнение прямой: y = mu * l + b
    sum_x = np.sum(l_cm)
    sum_y = np.sum(y)
    sum_x2 = np.sum(l_cm ** 2)
    sum_xy = np.sum(l_cm * y)

    # Знаменатель для МНК коэффициентов
    D = n * sum_x2 - sum_x ** 2

    mu = (n * sum_xy - sum_x * sum_y) / D
    intercept = (sum_x2 * sum_y - sum_x * sum_xy) / D

    # Расчет остаточной дисперсии точек относительно аппроксимирующей прямой
    y_pred = mu * l_cm + intercept
    residual_variance = np.sum((y - y_pred) ** 2) / (n - 2)

    # Абсолютная случайная погрешность углового коэффициента (mu) по МНК
    d_mu = np.sqrt(residual_variance * n / D)

    # Относительная погрешность mu в процентах
    eps_mu = (d_mu / mu) * 100

    print(f"{title:<15} | {mu:<12.4f} | {d_mu:<23.4f} | {eps_mu:.1f}%")

    # --- Построение индивидуального графика ---
    plt.figure(figsize=(8, 5.5))

    # Экспериментальные точки с вертикальными крестами ошибок логарифма
    plt.errorbar(l_cm, y, yerr=dy, xerr=0.02/30, fmt='+', color=material_data['color'],
                 ecolor='black', elinewidth=1.2, capsize=3, label='Экспериментальные точки')

    # Аппроксимирующая прямая МНК
    l_fit = np.linspace(0, max(l_cm) * 1.05, 100)
    y_fit = mu * l_fit + intercept
    plt.plot(l_fit, y_fit, '--', color='gray',
             label=f'МНК-линия ($\\mu$ = {mu:.3f} $\\pm$ {d_mu:.3f} $см^{{-1}}$)')

    # Настройки отображения графика
    plt.title(f'График зависимости $\\ln(I_0/I)$ от толщины образца ({title})', fontsize=12, pad=12)
    plt.xlabel('Толщина поглотителя $l$, см', fontsize=11)
    plt.ylabel('Логарифм ослабления $\\ln(I_0/I)$', fontsize=11)
    plt.xlim(0, max(l_cm) * 1.05)
    plt.ylim(0, max(y) * 1.1)
    plt.grid(True, linestyle=':', alpha=0.6)
    plt.legend(fontsize=10)
    plt.tight_layout()

    plt.show()

print("=" * 75)
