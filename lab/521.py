import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import find_peaks

# =============================================================================
# 1. ВВОД ЭКСПЕРИМЕНТАЛЬНЫХ ДАННЫХ ИЗ ТАБЛИЦЫ
# =============================================================================

# Данные для V_зад = 4 В
V_4 = np.array([0.04, 3.06, 6.04, 8.98, 12.01, 15.07, 17.97, 20.93, 22, 23.03,
                23.5, 23.75, 24, 24.2, 24.3, 24.75, 24.4, 25.1, 26, 27.17,
                30.1, 33, 36.02, 39, 40.2, 39.5, 41, 42, 43, 45,
                44.8, 48.2, 51.07, 54.1, 57.1, 60.3, 66, 71.7])
I_4 = np.array([6, 50, 108, 175.5, 251, 322, 384, 434, 445, 450,
                452, 457, 458, 465, 384, 386, 384, 393, 419, 447,
                527, 604, 660, 666, 651, 661, 643, 635, 632, 628,
                626, 643, 669, 702, 737, 763, 780, 798])

# Данные для V_зад = 6 В
V_6 = np.array([0.04, 4.04, 8.01, 12.1, 16.1, 20, 22.1, 22.73, 23.3, 23.9,
                24.3, 24.8, 25, 25.1, 25.96, 27.1, 28, 30, 33.9, 38.2,
                42.5, 40.1, 41.1, 41.75, 43.8, 47.3, 47.8, 48.3, 49, 50,
                54, 58, 62, 66, 71.5])
I_6 = np.array([2, 34, 117, 217, 317, 398, 426, 432, 437, 440,
                442, 444, 441, 280, 274.1, 296, 329, 403, 508, 566,
                522, 544, 537, 532, 504, 484, 481, 483, 486, 492,
                525, 562, 582, 585, 586])

# Данные для V_зад = 8 В
V_8 = np.array([0.04, 4, 8, 12, 16, 20.1, 22, 23, 24.3, 24.9,
                25.2, 25.5, 25.65, 27.3, 28.5, 28, 29, 30, 34, 38,
                39, 39.6, 40.1, 40.95, 41.5, 45, 48, 50, 50.5, 51.2,
                52, 54.99, 58.6, 61.2, 63.2, 64.7, 72.4, 62.8, 63.5])
I_8 = np.array([2, 5, 73, 167, 270, 363, 394, 407, 416, 418,
                416, 412, 190, 182, 198, 190, 212, 248, 380, 447,
                449, 445, 428, 420, 417, 377, 349, 344, 343, 346,
                350, 372, 400, 411, 415, 413, 401, 413, 413])

datasets = {
    '4 B': (V_4, I_4, 'blue'),
    '6 B': (V_6, I_6, 'green'),
    '8 B': (V_8, I_8, 'red')
}

# =============================================================================
# 2. ПОИСК ПИКОВ И РАСЧЕТ МЕЖПИКОВЫХ РАССТОЯНИЙ (Delta V)
# =============================================================================
all_delta_V = []

plt.figure(figsize=(10, 7))

for label, (V, I, color) in datasets.items():
    # Строим экспериментальные точки и соединяющую линию
    plt.plot(V, I, 'o-', label=f'$V_{{зад}} = {label}$', color=color, markersize=4, alpha=0.7)

    # Находим индексы локальных максимумов (параметры подбираются под рельеф ВАХ)
    # distance гарантирует, что пики не будут слишком близко друг к другу
    peaks, _ = find_peaks(I, distance=5, prominence=15)

    # Отмечаем найденные пики крестиками на графике
    plt.plot(V[peaks], I[peaks], "x", color='black', markersize=10, mew=2)
    for p in peaks:
        plt.text(V[p], I[p] + 15, f'{V[p]} В', ha='center', fontsize=9, weight='bold')

    # Вычисляем расстояния между последовательными пиками для данного графика
    if len(peaks) > 1:
        diffs = np.diff(V[peaks])
        all_delta_V.extend(diffs)
        print(f"Потенциалы пиков при V_зад = {label}: {V[peaks]} В -> Шаги: {diffs} В")

    # Оформление графика
    plt.title(f'Вольтамперная характеристика в статическом режиме ({label})', fontsize=12, pad=15)
    plt.xlabel('Ускоряющее напряжение $V_a$, В', fontsize=11)
    plt.ylabel('Ток коллектора $I_k$, мкА', fontsize=11)
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.legend(fontsize=11)
    plt.show()

# =============================================================================
# 3. СТАТИСТИЧЕСКАЯ ОБРАБОТКА И РАСЧЕТ ПОГРЕШНОСТИ
# =============================================================================
delta_V_array = np.array(all_delta_V)
N = len(delta_V_array)

# Среднее значение шага напряжений
V_mean = np.mean(delta_V_array)

# Среднеквадратичное отклонение отдельного измерения (СКО)
S_x = np.std(delta_V_array, ddof=1)

# Случайная погрешность среднего (СКО среднего)
S_mean = S_x / np.sqrt(N)

# Коэффициент Стьюдента для доверительной вероятности P = 0.95 и f = N - 1 степеней свободы
# Для N = 5 (f = 4) t = 2.78
t_student = 2.78
t_error = t_student * S_mean

# Приборная погрешность вольтметра (принимаем за половину цены деления шкалы или шага, например, 0.1 В)
instrument_error = 0.1
# Полная абсолютная погрешность
total_absolute_error = np.sqrt(t_error ** 2 + instrument_error ** 2)

# Относительная погрешность
relative_error = (total_absolute_error / V_mean) * 100

# Энергия в эВ численно равна потенциалу в В
E_mean = V_mean
delta_E = total_absolute_error

print("\n" + "=" * 50)
print("РЕЗУЛЬТАТЫ СТАТИСТИЧЕСКОГО АНАЛИЗА:")
print("=" * 50)
print(f"Всего найденных периодов (N): {N}")
print(f"Все значения Delta V: {delta_V_array} В")
print(f"Среднее межпиковое напряжение: {V_mean:.2f} В")
print(f"Абсолютная погрешность (P=0.95): {total_absolute_error:.2f} В")
print(f"Относительная погрешность: {relative_error:.1f}%")
print(f"\nЭнергия первого уровня атома гелия: E = ({E_mean:.1f} ± {delta_E:.1f}) эВ")
print("=" * 50)
